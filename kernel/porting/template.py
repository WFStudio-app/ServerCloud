"""Port scaffold generator — заготовка для расширения кроссплатформенности.

`scaffold_port()` creates a ready-to-fill directory for a brand-new port:

    ports/<vendor>/<target-id>/
        port.py          Port class wired into the HAL (compiles as-is)
        hal_impl.py      stub implementing every HAL method
        manifest.data    metadata file (same format Settings reads from
                         upd_file/*.data: key=value lines)
        README.md        checklist for the porter

It also appends the new Target to PORT_MATRIX at runtime and can write a
`matrix_add.snippet` so the maintainer can paste the permanent entry into
ports.py.  This is the official way to grow beyond the current 20 targets.
"""

import os
from datetime import date

from .ports import PORT_MATRIX, Target, Urgency

_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))          # repo root (…/ServerCloud)

_TEMPLATES = {
    "phone-android": dict(kind="phone", arch="arm64", os_base="android",
                          abi="syscall", page_size=4096),
    "phone-ios": dict(kind="phone", arch="arm64", os_base="ios",
                      abi="mach_trap", page_size=16384),
    "handheld-steamos": dict(kind="handheld", arch="x86_64", os_base="linux",
                             abi="syscall", page_size=4096),
    "desktop-linux": dict(kind="desktop", arch="x86_64", os_base="linux",
                          abi="syscall", page_size=4096),
    "server-bare": dict(kind="server", arch="x86_64", os_base="bare",
                        abi="syscall", page_size=4096),
    "embedded-riscv": dict(kind="server", arch="riscv64", os_base="bare",
                           abi="syscall", page_size=4096),
}


def list_templates():
    return sorted(_TEMPLATES)


